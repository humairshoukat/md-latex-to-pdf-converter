"""Generate native MathML alphabet substitutions from Python's Unicode database."""
import json
from pathlib import Path
import unicodedata

styles = {
    'BOLD': 'bold', 'ITALIC': 'italic', 'BOLD ITALIC': 'bold-italic',
    'SCRIPT': 'script', 'BOLD SCRIPT': 'bold-script', 'FRAKTUR': 'fraktur',
    'DOUBLE-STRUCK': 'double-struck', 'BOLD FRAKTUR': 'bold-fraktur',
    'SANS-SERIF': 'sans-serif', 'SANS-SERIF BOLD': 'bold-sans-serif',
    'SANS-SERIF ITALIC': 'sans-serif-italic',
    'SANS-SERIF BOLD ITALIC': 'sans-serif-bold-italic', 'MONOSPACE': 'monospace',
}
variants = {style: {} for style in styles.values()}
for point in [*range(0x2100, 0x2150), *range(0x1D400, 0x1D800)]:
    char = chr(point)
    name = unicodedata.name(char, '').removeprefix('MATHEMATICAL ')
    decomposition = unicodedata.decomposition(char).split()
    if len(decomposition) != 2 or decomposition[0] != '<font>':
        continue
    for prefix in sorted(styles, key=len, reverse=True):
        if name.startswith(prefix + ' '):
            variants[styles[prefix]][chr(int(decomposition[1], 16))] = char
            break
# These legacy letterlike symbols have names that omit their alphabet style.
for base, symbol in zip('BEFHILMR', 'ℬℰℱℋℐℒℳℛ'):
    variants['script'][base] = symbol
for base, symbol in zip('ego', 'ℯℊℴ'):
    variants['script'][base] = symbol
variants['italic']['h'] = 'ℎ'
output = '// Generated by scripts/generate-math-variants.py.\n'
output += 'const variants = ' + json.dumps(variants, ensure_ascii=False, separators=(',', ':')) + ';\n\n'
output += '''export function nativeMathVariants(mathml) {
  return mathml.replace(/<(mi|mn|mo|mtext) mathvariant="([^"]+)"([^>]*)>([^<]*)<\\/\\1>/g,
    (element, tag, variant, attributes, content) => {
      const alphabet = variants[variant];
      if (!alphabet) return element;
      const text = Array.from(content, (char) => alphabet[char] ?? char).join('');
      return `<${tag} mathvariant="normal"${attributes}>${text}</${tag}>`;
    });
}
'''
Path('static/vendor/math-variants.js').write_text(output)
